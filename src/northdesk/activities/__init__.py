"""Temporal activities: everything that does I/O or can fail for a moment.

The agent's model and tool activities are generated by Pydantic AI (see agent/agent.py).
"""

import logging
from functools import cache

from pydantic import BaseModel
from temporalio import activity
from temporalio.exceptions import ApplicationError

from northdesk import data
from northdesk.config import get_settings
from northdesk.domain import ActionResult, Decision, Ticket, TicketContext, Triage
from northdesk.services.classifier import Classifier, ClassifierError, FakeClassifier, JevClassifier
from northdesk.services.helpdesk import FakeHelpdesk, HelpdeskError

log = logging.getLogger(__name__)


class ClassifyInput(BaseModel):
    ticket: Ticket
    context: TicketContext


class ActionRequest(BaseModel):
    ticket_id: str
    decision: Decision


def _ids(ticket_id: str) -> dict:
    return {"ticket_id": ticket_id, "workflow_id": activity.info().workflow_id, "attempt": activity.info().attempt}


@cache
def classifier() -> Classifier:
    settings = get_settings()
    if settings.llm_mode == "fake":
        return FakeClassifier()
    return JevClassifier(settings.openrouter_api_key, settings.classifier_model)


@cache
def helpdesk() -> FakeHelpdesk:
    settings = get_settings()
    return FakeHelpdesk(settings.helpdesk_store, failure_rate=settings.helpdesk_failure_rate)


@activity.defn
async def load_context(ticket: Ticket) -> TicketContext:
    customer = data.get_customer(ticket.customer_id)
    log.info("context loaded", extra={**_ids(ticket.ticket_id), "customer_found": customer is not None})
    return TicketContext(
        customer=customer,
        invoices=data.get_invoices(ticket.customer_id) if customer else [],
        kb_articles=data.kb_articles(),
    )


@activity.defn
async def classify_ticket(request: ClassifyInput) -> Triage:
    try:
        triage = await classifier().classify(request.ticket, request.context)
    except ClassifierError as exc:
        raise ApplicationError(str(exc), type="ClassifierError", non_retryable=True) from exc
    answers = {q: f"{a.choice} ({a.confidence:.2f})" for q, a in triage.answers.items()}
    log.info("ticket classified", extra={**_ids(request.ticket.ticket_id), "model": triage.model, "answers": answers})
    return triage


@activity.defn
async def execute_action(request: ActionRequest) -> ActionResult:
    return perform_action(helpdesk(), request)


def perform_action(desk: FakeHelpdesk, request: ActionRequest) -> ActionResult:
    """Body of execute_action, with the Helpdesk passed in so tests can use their own."""
    ids = _ids(request.ticket_id)
    # One key per workflow and action: a retried activity hits the same key and is not done twice.
    key = f"{ids['workflow_id']}:{request.decision.action.type}"
    log.info("calling helpdesk", extra={**ids, "action": request.decision.action.type})
    try:
        result = desk.perform(key, request.ticket_id, request.decision.action)
    except HelpdeskError as exc:
        raise ApplicationError(str(exc), type="HelpdeskError", non_retryable=True) from exc
    log.info("helpdesk done", extra={**ids, "reference": result.reference})
    return result
